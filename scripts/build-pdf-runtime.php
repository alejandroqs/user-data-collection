<?php
/** Build-only: isolate locked dependencies and generate a relative, plugin-owned autoloader. */
$root = dirname(__DIR__);
chdir($root);
$runtime = $root . '/runtime/pdf';
if (is_dir($runtime)) {
    if (str_replace('\\', '/', realpath($runtime)) !== str_replace('\\', '/', realpath($root)) . '/runtime/pdf') {
        throw new RuntimeException('Generated runtime resolves outside its expected directory.');
    }
    // This fixed generated directory is never used for user data.
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($runtime, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
    foreach ($iterator as $file) {
        if ($file->isLink()) { throw new RuntimeException('Unexpected symlink in runtime.'); }
        $file->isDir() ? rmdir($file->getPathname()) : unlink($file->getPathname());
    }
    rmdir($runtime);
}
$command = escapeshellarg(PHP_BINARY) . ' ' . escapeshellarg($root . '/tools/pdf-build/vendor/bin/php-scoper') .
    ' add-prefix --config=' . escapeshellarg($root . '/tools/pdf-build/scoper.inc.php') .
    ' --output-dir=' . escapeshellarg($runtime . '/vendor') . ' --force --no-interaction';
passthru($command, $status);
if (0 !== $status) { exit($status); }

$prefixes = require $root . '/vendor/composer/autoload_psr4.php';
$classes = require $root . '/vendor/composer/autoload_classmap.php';
$maps = ['prefixes' => [], 'classes' => []];
foreach ($prefixes as $prefix => $directories) {
    foreach ($directories as $directory) {
        $maps['prefixes']['UDCPdfVendor\\' . $prefix][] = str_replace('\\', '/', substr($directory, strlen($root) + 1));
    }
}
foreach ($classes as $class => $path) {
    if (0 === strpos($class, 'Composer\\')) { continue; }
    $maps['classes']['UDCPdfVendor\\' . $class] = str_replace('\\', '/', substr($path, strlen($root) + 1));
}
$loader = <<<'PHP'
<?php
// Generated by scripts/build-pdf-runtime.php; loads only isolated PDF classes.
$maps = MAPS;
spl_autoload_register(static function ($class) use ($maps) {
    if (isset($maps['classes'][$class])) { require __DIR__ . '/' . $maps['classes'][$class]; return; }
    foreach ($maps['prefixes'] as $prefix => $directories) {
        if (0 !== strpos($class, $prefix)) { continue; }
        foreach ($directories as $directory) {
            $path = __DIR__ . '/' . $directory . '/' . str_replace('\\', '/', substr($class, strlen($prefix))) . '.php';
            if (is_file($path)) { require $path; return; }
        }
    }
});
PHP;
file_put_contents($runtime . '/autoload.php', str_replace('MAPS', var_export($maps, true), $loader));
// Scoper's generated loader exposes aliases; our isolated loader replaces it.
if (is_file($runtime . '/vendor/scoper-autoload.php')) { unlink($runtime . '/vendor/scoper-autoload.php'); }
$manifest = [];
$iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($runtime, FilesystemIterator::SKIP_DOTS));
foreach ($iterator as $file) {
    if (!$file->isFile() || $file->isLink()) { throw new RuntimeException('Unexpected runtime entry.'); }
    $relative = str_replace('\\', '/', substr($file->getPathname(), strlen($runtime) + 1));
    $manifest[$relative] = hash_file('sha256', $file->getPathname());
}
ksort($manifest);
file_put_contents($runtime . '/manifest.json', json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
echo 'Built isolated PDF runtime (' . count($manifest) . ' files).' . PHP_EOL;
